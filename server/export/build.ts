import ExcelJS from "exceljs";
import { toCsv, neutralise } from "../../shared/csvSafe.ts";
import { formatInZone } from "../../shared/normalize.ts";

export type Cell = string | number | boolean | null;
export interface Sheet {
  name: string;
  headers: string[];
  rows: Cell[][];
  /** indexes of columns holding decimal amounts/quantities (exported as numbers / unquoted in CSV) */
  numeric: number[];
}
export interface ExportBundleData {
  summary: Sheet;
  lines: Sheet;
  exceptions: Sheet;
  audit: Sheet;
  meta: [string, string][];
}

export const EXPORT_DISCLAIMER = "Generated by AP Document Intelligence & Three-Way Match from SYNTHETIC demo data. This file is a review/approval record. No payment was made or initiated and nothing was posted to any ledger.";

export function sheetToCsv(sheet: Sheet): string {
  return toCsv(sheet.headers, sheet.rows, sheet.numeric);
}

export async function buildXlsx(data: ExportBundleData, sheetsWanted: ("summary" | "lines" | "exceptions" | "audit")[]): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = "AP Document Intelligence (synthetic demo)";
  wb.created = new Date(0);
  const readme = wb.addWorksheet("About this file");
  readme.columns = [{ width: 28 }, { width: 100 }];
  readme.addRow(["Notice", EXPORT_DISCLAIMER]);
  for (const [k, v] of data.meta) readme.addRow([neutralise(k), neutralise(v)]);
  readme.getColumn(1).font = { bold: true };
  readme.eachRow((r) => (r.alignment = { vertical: "top", wrapText: true }));

  for (const key of sheetsWanted) {
    const sheet = data[key];
    const ws = wb.addWorksheet(sheet.name, { views: [{ state: "frozen", ySplit: 1 }] });
    ws.addRow(sheet.headers);
    const head = ws.getRow(1);
    head.font = { bold: true, color: { argb: "FFFFFFFF" } };
    head.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF24323F" } };
    for (const r of sheet.rows) {
      ws.addRow(r.map((c, i) => {
        if (c === null) return null;
        if (sheet.numeric.includes(i) && typeof c === "string" && /^-?\d+(\.\d+)?$/.test(c)) return Number(c);
        return typeof c === "string" ? neutralise(c) : c;
      }));
    }
    sheet.headers.forEach((h, i) => {
      const col = ws.getColumn(i + 1);
      const longest = Math.max(h.length, ...sheet.rows.slice(0, 200).map((r) => String(r[i] ?? "").length));
      col.width = Math.min(60, Math.max(10, longest + 2));
      if (sheet.numeric.includes(i)) col.numFmt = "#,##0.00##";
    });
    ws.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: sheet.headers.length } };
  }
  return Buffer.from(await wb.xlsx.writeBuffer());
}

export const inZone = (iso: string | null | undefined, tz: string) => (iso ? formatInZone(iso, tz) : "");
